/** ControlPlane SPI: the lane's only application-facing port (claim / sync / complete).
 * IDs are opaque strings; their format, the wire protocol and authentication belong to the
 * implementation. Credentials carried by a lease live in runtime memory only. */
import type { OutputRejection } from "../common/output-files.js";
import type { ModelWire } from "./model-upstream.js";
import type { ConfirmOutcome, ConfirmRequest } from "./tool-provider.js";
import type { WebAccessPolicy } from "./web-access.js";

export interface LeaseProof {
  readonly job_id: string;
  readonly generation: number;
  readonly claim_token: string;
}

export interface ClaimRequest {
  readonly runtime_id: string;
  readonly lanes: readonly string[];
  readonly claim_token: string;
  readonly max_jobs?: number;
  readonly wait_ms?: number;
}

export interface RunIdentity {
  readonly user_id: string;
  /** Tenant membership of the Run owner; absent from older control planes, then the user ID
   * stands in. */
  readonly tenant_access_id?: string;
  /** Opaque identity attributes the control plane hands to its own tool providers (e.g. routing
   * hints). The core passes them through without interpreting them. */
  readonly attributes: Readonly<Record<string, string>>;
}

export interface HistoryMessage {
  readonly role: "user" | "assistant";
  readonly content: string;
}

export interface FrozenRunInput {
  readonly prompt: string;
  readonly history: readonly HistoryMessage[];
  readonly ui_context?: Readonly<Record<string, unknown>>;
  /**
   * Assistant profile guidance frozen by the Engine (published agent definition plus the member's
   * own preferences). Delivered to the model as labelled context data, never as system instructions.
   */
  readonly instructions?: string;
  /** Members the user picked with `@` in this message, as confirmed by the control plane (active
   * internal members of the tenant), in order. A mention only points at someone; it never means
   * "do this for them" by itself. */
  readonly mentions?: readonly Mention[];
}

export interface Mention {
  readonly member_id: string;
  readonly name: string;
  readonly is_digital?: boolean;
}

export const RUN_SOURCE_TYPES = ["conversation", "task", "todo", "schedule", "mail"] as const;

/** Where a Run comes from: `conversation` = submitted by the user in a conversation, `task` = a task
 * assigned to the Run's subject (a digital employee); other types get no delegation tool for now.
 * `ref` is the control plane's own reference (opaque to the Worker; may be absent). */
export interface RunSource {
  readonly type: (typeof RUN_SOURCE_TYPES)[number];
  readonly ref?: string;
}

export interface ExpiringSecret {
  readonly value: string;
  readonly expires_at: number;
}

export const REASONING_EFFORTS = ["low", "medium", "high"] as const;
export type ReasoningEffort = (typeof REASONING_EFFORTS)[number];

export interface ModelService {
  readonly base_uri: string;
  /** Upstream model API; must be the wire the Run's Harness speaks. */
  readonly wire_api: ModelWire;
  readonly model: string;
  /** Lane-specific reasoning effort chosen by the control plane; absent = Harness default. */
  readonly reasoning_effort?: ReasoningEffort;
  readonly api_key: string;
}

/** A file of the Run's conversation (an upload, or a file generated by an earlier Run) that the
 * Worker places into the sandbox. Listed newest first; the control plane marks files it did not
 * sign (over its limits, unavailable) as not loaded, and they are only named to the model. */
export interface LeaseFile {
  readonly file_id: string;
  /** Original file name (user data: never a path, never logged). */
  readonly name: string;
  readonly content_type?: string;
  /** Declared size in bytes; a download of another size is discarded. */
  readonly size?: number;
  /** `input`: uploaded by the user; `output`: generated by an earlier Run. */
  readonly relation: "input" | "output";
  readonly loaded: boolean;
  /** Signed short-lived https download URL, present only when loaded. A bearer secret like the
   * agent token: never logged, never reported, never passed to a sandbox or a prompt. */
  readonly url?: string;
  readonly expires_at?: number;
}

export interface Lease {
  readonly job_id: string;
  readonly generation: number;
  readonly lease_until: number;
  readonly deadline_at: number;
  readonly run: {
    readonly run_id: string;
    readonly tenant_id: string;
    readonly conversation_id: string;
    readonly run_no?: number;
    readonly execution_profile: "sandbox";
    /** Opaque Harness ID (agent CLI) selected by the control plane; the composition root maps it to
     * a Driver and the sandbox to a CLI image. */
    readonly harness: string;
    /** Web access granted to the Run; implementations map an absent grant to WEB_ACCESS_OFF. */
    readonly web_access: WebAccessPolicy;
    /** Tools this Run may use (the control plane narrows per Run). The Worker intersects it with its
     * own enabled tools: it only narrows. Absent = every enabled tool. */
    readonly tools?: readonly string[];
    /** Patterns of tool operations the user must approve before they run (approval bridge); the
     * tool provider defines what they match. Absent or empty = every call runs directly. */
    readonly confirm_operations?: readonly string[];
    /** File mode (the CLI may read and write the workspace and run commands; generated files go
     * to its outputs directory). Absent from older control planes: then file mode follows whether
     * the lease carries conversation files. */
    readonly file_tools?: boolean;
    /** Source of the Run: a message in a conversation, or a task assigned to the Run's subject.
     * Absent from older control planes; without it no delegation tool is offered (see ControlTool). */
    readonly source?: RunSource;
    readonly identity: RunIdentity;
    readonly input: FrozenRunInput;
    readonly input_digest: string;
  };
  /** Never logged, never passed to a sandbox. */
  readonly credentials: {
    readonly agent_token: ExpiringSecret;
    readonly model_service: ModelService;
    /** Conversation files to stage for this Run; absent = none. */
    readonly files?: readonly LeaseFile[];
  };
}

/** A claimed lease after validation: `proof` settles it; `lease` is absent when its content was
 * rejected (the Run is then completed as failed). */
export interface ClaimedLease {
  readonly proof: LeaseProof;
  readonly lease?: Lease;
  /** Codes of content the parser tolerated rather than rejected (e.g. a list truncated to its
   * limit); the lane logs them. Never content. */
  readonly adjustments?: readonly string[];
}

export type WorkerEventType =
  | "assistant.message.delta"
  | "runtime.item.started"
  | "runtime.item.completed"
  | "runtime.approval.denied"
  | "plan.updated"
  | "plan.delta"
  /** Structured report of a task Run (from the report_task control plane tool). */
  | "task.reported";

export interface WorkerEvent {
  readonly type: WorkerEventType;
  readonly data?: Readonly<Record<string, unknown>>;
}

export interface ActionRequest {
  readonly action_id: string;
  readonly op: string;
  readonly arguments?: Readonly<Record<string, unknown>>;
}

export interface SyncRequest extends LeaseProof {
  readonly started?: boolean;
  readonly offset?: number;
  readonly events?: readonly WorkerEvent[];
  readonly action_requests?: readonly ActionRequest[];
  readonly awaiting_actions?: readonly string[];
  readonly wait_ms?: number;
}

export interface ActionReceipt {
  readonly action_id: string;
  readonly status: "SETTLED" | "VOID";
  readonly receipt?: Readonly<Record<string, unknown>>;
}

export interface SyncResponse {
  readonly lease_until: number;
  readonly cancel: boolean;
  readonly event_offset: number;
  readonly action_receipts: readonly ActionReceipt[];
  /**
   * Renewed control plane token. Absent only together with `cancel: true`, when the Run's
   * subject lost access: the Engine stops renewing and the Worker must drop its current token.
   */
  readonly agent_token?: ExpiringSecret;
}

export interface Outcome {
  readonly status: "SUCCEEDED" | "FAILED" | "CANCELLED";
  readonly answer?: string;
  readonly error?: { readonly code: string; readonly message: string };
  readonly usage?: { readonly input_tokens: number; readonly output_tokens: number };
}

export interface CompleteRequest extends LeaseProof {
  readonly outcome: Outcome;
}

export type CompleteResult = "ACCEPTED" | "ALREADY_ACCEPTED" | "ACCEPTED_AS_CANCELLED";

/** One generated file reported before settlement: its content, or why it was not delivered
 * (exactly one of `content_base64` and `rejected`). */
export interface OutputRequest extends LeaseProof {
  /** Sandbox-relative path, `outputs/<name>`; links in the answer refer to it. */
  readonly path: string;
  /** Original file name (user data: never logged). */
  readonly name: string;
  /** Type the Worker determined from extension and content. */
  readonly content_type?: string;
  readonly content_base64?: string;
  readonly rejected?: OutputRejection;
}

/** The stored file (absent for a rejected report). */
export interface OutputResult {
  readonly file_id?: string;
  readonly name?: string;
  readonly content_type?: string;
  readonly size?: number;
}

/** Neutral fault codes the lane acts on. Implementations map their own codes onto these; any
 * other fault is reported as the implementation's sanitized code. */
export const FAULT_LEASE_LOST = "lease_lost";
export const FAULT_EVENT_OFFSET_GAP = "event_offset_gap";
export const FAULT_COMPLETE_REJECTED = "complete_rejected";
export const FAULT_INVALID_INPUT = "invalid_input";
export const FAULT_EXECUTION_DISABLED = "execution_disabled";
/** The Run has reached the control plane's limit of generated files. */
export const FAULT_OUTPUT_LIMIT = "output_limit";

/** Never carries response bodies, URLs or credentials: only a code, a fault code and, for an
 * offset gap, the expected offset. `CONTROL_PLANE_REJECTED` is a definite verdict on the request
 * (named by `fault`); `CONTROL_PLANE_FAULT` is any other error the control plane reported. */
export class ControlPlaneError extends Error {
  constructor(
    readonly code:
      | "CONTROL_PLANE_UNAVAILABLE"
      | "CONTROL_PLANE_PROTOCOL"
      | "CONTROL_PLANE_FAULT"
      | "CONTROL_PLANE_REJECTED",
    readonly fault?: string,
    readonly expected?: number
  ) {
    super(fault ? `${code}: ${fault}` : code);
    this.name = "ControlPlaneError";
  }
}

/** Reasons the Worker itself reports for a client action that did not run. */
export type ClientActionFailure = "unavailable" | "invalid_argument" | "timeout";

/** One turn's offer of a client action: what the model sees and what may be relayed. */
export interface ClientActionOffer {
  readonly description: string;
  /** JSON Schema of the arguments (an object schema). */
  readonly inputSchema: Readonly<Record<string, unknown>>;
  /** Bounded argument check before relaying; returns the reason (shown to the model) when
   * rejected. */
  checkArguments(value: unknown): string | null;
}

/** Approval bridge over the client action channel: how to ask the user's client to approve one
 * tool call, and how to read its answer. The control plane defines both. */
export interface ClientConfirmation {
  /** The action (operation and arguments) that asks the client to approve `request`. */
  request(request: ConfirmRequest): {
    readonly op: string;
    readonly arguments: Readonly<Record<string, unknown>>;
  };
  /** The verdict in the client's receipt (or in the Worker's failure receipt). Anything that is
   * not a clear approval must not return `approved`. */
  verdict(actionId: string, receipt: unknown): ConfirmOutcome;
}

/** A tool the model calls but the user's client executes (e.g. actions on an open page). The tool
 * gateway serves it to the Run's CLI over MCP like any other tool; requests and receipts travel
 * through sync. The control plane defines the tool and its receipt format. */
export interface ClientActionTool {
  /** Tool name in the tool gateway's MCP namespace. */
  readonly name: string;
  /** This turn's offer, judged from the Run's prompt envelope; undefined = not offered. */
  offer(input: {
    readonly prompt: string;
    readonly promptFormat?: string;
  }): ClientActionOffer | undefined;
  /** Validate a client receipt before the model sees it; throws when invalid. */
  checkReceipt(actionId: string, receipt: unknown): unknown;
  /** Receipt the Worker returns to the model when the action did not run. */
  failure(actionId: string | undefined, reason: ClientActionFailure, message: string): unknown;
  /** Approval bridge for this turn, judged from the Run's prompt envelope (whether a client can
   * answer at all); undefined = no confirmation can be asked, so calls needing one do not run.
   * Independent of whether the tool itself is offered. */
  confirmation?(input: {
    readonly prompt: string;
    readonly promptFormat?: string;
  }): ClientConfirmation | undefined;
  /** Whether anyone can answer this Run's client actions at all, judged from the lease (e.g. not
   * for an assigned task: no browser is online). When false the action is not offered, the turn
   * is told nothing about it, and calls that need approval are refused at once as `unattended`
   * without relaying anything. Absent = always attended. */
  attended?(lease: Omit<Lease, "credentials">): boolean;
}

/** Result of one control plane tool call: text for the model; `failed` = it was not done (returned
 * with MCP isError). */
export interface ControlToolResult {
  readonly text: string;
  readonly failed?: boolean;
  /** Diagnostic result code (e.g. the control plane's fault code): lane log only, never the model. */
  readonly code?: string;
}

/** What the lane hands a control plane tool for one call. */
export interface ControlToolCall {
  /** The Run's lease proof, carried by every control plane call. */
  readonly proof: LeaseProof;
  /** The CLI's tool call ID (from the MCP `_meta`; an unchecked external string); absent when the
   * CLI sends none. A resend of the same call carries the same ID, so it can derive an
   * idempotency key. */
  readonly callId?: string;
  /** Report one event through sync: after the events produced so far, at contiguous offsets. The
   * lane keeps resending an unconfirmed one before it settles (complete) while the lease leaves
   * room, and logs it when it gives up. At the per-Run limit the event replaces the last unsent one
   * of its type. False = not taken (the Run is ending, the lease is lost, or the limit is reached
   * with nothing to replace). */
  report(event: WorkerEvent): boolean;
  /** Aborted when the call ends (MCP request closed, Run over). */
  readonly signal: AbortSignal;
}

/** One control plane tool as offered to a Run: description, arguments and execution. */
export interface ControlToolOffer {
  readonly description: string;
  /** JSON Schema of the arguments (an object schema). */
  readonly inputSchema: Readonly<Record<string, unknown>>;
  /** Optional short note for the model, placed with the mentions (system instructions or context
   * data). */
  readonly note?: string;
  /** Run one call. Failures are results too (never thrown): a control plane refusal does not change
   * the Run's outcome. */
  call(args: unknown, call: ControlToolCall): Promise<ControlToolResult>;
}

/**
 * Control plane tool: called by the model and completed by the Run's own lane through the control
 * plane service (SERVICE principal plus lease proof), never with the Run owner's token (e.g. task
 * APIs the agent token may not call). Served over MCP by the tool gateway like the client action:
 * visible and callable for the Run it was offered to only, gone when the Run ends.
 *
 * The control plane decides per lease whether to offer it (`offer`); the Worker's
 * SANDLANE_ENABLED_TOOLS can remove it, the lease's `run.tools` (member settings) does not narrow
 * it: the lease already says whether it applies (e.g. `run.source`).
 */
export interface ControlTool {
  /** Tool name in the tool gateway's MCP namespace; never a gateway tool's or the client action's. */
  readonly name: string;
  /** This Run's offer; undefined = not offered. Reads only non-secret lease content. */
  offer(lease: Omit<Lease, "credentials">): ControlToolOffer | undefined;
}

export interface ControlPlane {
  /** Long poll. Returns raw leases; each is validated individually through readLease(). */
  claim(request: ClaimRequest, signal: AbortSignal): Promise<readonly unknown[]>;
  /** Validate one raw lease. Undefined when not even a settleable proof can be read. */
  readLease(raw: unknown, claimToken: string): ClaimedLease | undefined;
  sync(request: SyncRequest, signal: AbortSignal): Promise<SyncResponse>;
  complete(request: CompleteRequest, signal: AbortSignal): Promise<CompleteResult>;
  /** Report one generated file (stored for the Run's owner) or one refused file, before
   * complete; absent when the control plane takes no generated files. Never retried by the
   * lane: a lost reply may already have stored the file. */
  output?(request: OutputRequest, signal: AbortSignal): Promise<OutputResult>;
  /** Client action relayed through sync and served as an MCP tool; absent when the control plane
   * offers none. */
  readonly clientActions?: ClientActionTool;
  /** Control plane tools (see ControlTool); absent when the control plane offers none. */
  readonly controlTools?: readonly ControlTool[];
}
