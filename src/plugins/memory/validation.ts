/** Byte budgets include UTF-8, not JavaScript character counts. */
export function boundedText(text: string, bytes: number): void {
  if (typeof text !== "string" || !text.trim() || Buffer.byteLength(text) > bytes)
    throw new Error("MEMORY_TEXT_LIMIT");
}
